/**
 * `pnpm db:docs` — regenerate docs/DATA-MODEL.md from the live database, so the doc can never drift from
 * the schema. Purpose/owner/phase come from each table's COMMENT ("purpose | written by: x | phase: n");
 * scope and access come from private.policy_registry. CI fails if the committed file is stale.
 */
import { writeFileSync } from 'node:fs';
import pg from 'pg';

const url = process.env.DATABASE_URL ?? 'postgresql://postgres:postgres@127.0.0.1:54322/postgres';
const pool = new pg.Pool({ connectionString: url, max: 1 });

interface TableRow {
  table_name: string;
  kind: string;
  scope: string | null;
  read_roles: string[] | null;
  write_roles: string[] | null;
  notes: string | null;
  comment: string | null;
  pk: string[] | null;
  fks: string[] | null;
  has_org: boolean;
  has_branch: boolean;
}

const rows = (
  await pool.query<TableRow>(
    `select r.table_name, r.kind, r.scope, r.read_roles::text[] as read_roles, r.write_roles::text[] as write_roles, r.notes,
            obj_description(c.oid, 'pg_class') as comment,
            (select array_agg(a.attname order by k.o) from pg_constraint con
               cross join lateral unnest(con.conkey) with ordinality k(n, o)
               join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.n
             where con.conrelid = c.oid and con.contype = 'p') as pk,
            (select array_agg(distinct fc.relname order by fc.relname) from pg_constraint con
               join pg_class fc on fc.oid = con.confrelid join pg_namespace fn on fn.oid = fc.relnamespace
             where con.conrelid = c.oid and con.contype = 'f' and fn.nspname = 'public' and fc.relname not in ('organizations')) as fks,
            exists (select 1 from pg_attribute a where a.attrelid = c.oid and a.attname = 'org_id' and not a.attisdropped) as has_org,
            exists (select 1 from pg_attribute a where a.attrelid = c.oid and a.attname = 'branch_id' and not a.attisdropped) as has_branch
     from private.policy_registry r
     join pg_class c on c.relname = r.table_name and c.relnamespace = 'public'::regnamespace
     order by r.table_name`,
  )
).rows;

const functions = (
  await pool.query<{ name: string; args: string; doc: string | null }>(
    `select p.proname as name, pg_get_function_arguments(p.oid) as args, obj_description(p.oid, 'pg_proc') as doc
     from pg_proc p where p.pronamespace = 'public'::regnamespace and p.prokind = 'f' order by p.proname`,
  )
).rows;

const parse = (comment: string | null) => {
  const [purpose = '', ...rest] = (comment ?? '').split(' | ');
  const meta = Object.fromEntries(rest.map((s) => s.split(': ') as [string, string]));
  return {
    purpose: purpose.trim(),
    writtenBy: meta['written by'] ?? '—',
    phase: meta.phase ?? '—',
  };
};

const scopeOf = (t: TableRow): string => {
  if (t.kind === 'platform_read') return 'platform (no tenant data)';
  if (t.kind === 'service_only')
    return t.has_org ? 'org · service only' : 'platform · service only';
  if (t.table_name === 'organizations') return 'org (the tenant)';
  return t.has_branch ? 'org + branch' : t.has_org ? 'org' : 'user';
};

const accessOf = (t: TableRow): string => {
  if (t.kind === 'service_only') return 'no client access';
  if (t.kind === 'platform_read') return 'read: signed-in users; write: none';
  if (t.kind === 'custom') return `custom — ${t.notes ?? 'see policies'}`;
  const write =
    (t.write_roles ?? []).length > 0 ? (t.write_roles ?? []).join(', ') : 'service role only';
  const note = t.notes ? ` (${t.notes})` : '';
  return `read: ${(t.read_roles ?? []).join(', ')}; write: ${write}${note}`;
};

const esc = (s: string) => s.replaceAll('|', '\\|').replaceAll('\n', ' ');

const lines: string[] = [
  '# Xedine — Data Model (generated)',
  '',
  '> **Generated by `pnpm db:docs` from the live schema — do not edit by hand.** CI fails if this file is stale.',
  "> Purpose, owner module and phase come from each table's `COMMENT`; scope and access come from `private.policy_registry`.",
  '',
  '## Conventions',
  '- Every tenant table carries `org_id` (and `branch_id` where relevant) with RLS enabled; policies call the helpers `private.is_org_member`, `has_role`, `can_access_branch`, `can_access_branch_role`, `can_see_money`.',
  "- Foreign keys between tenant tables are **composite** `(org_id, id)`, so a row can never reference another tenant's data. A test enforces this.",
  '- Money is `bigint` poisha (৳1 = 100), always in columns named `*_poisha`. Order lines store the full VAT decomposition (ADR 0005). Quantities are `numeric` in base units (g, ml, pcs).',
  '- Timestamps are `timestamptz` (UTC). `orders.business_date` is set at insert from `placed_at` and the branch cutoff, and never rewritten (ADR 0006).',
  '- Cost, margin, profit and finding-impact tables are readable by owner + accountant only (ADR 0007).',
  '- `audit_log`, `order_events` and `price_history` are append-only (triggers reject UPDATE/DELETE/TRUNCATE).',
  '- Access shown is the role list from the policy engine; "service role only" means jobs and webhooks, always with explicit `org_id` filters.',
  '',
  `## Tables (${rows.length})`,
  '',
  '| Table | Purpose | Scope | Access | Key columns | Written by · Phase |',
  '|---|---|---|---|---|---|',
];

for (const t of rows) {
  const { purpose, writtenBy, phase } = parse(t.comment);
  const keys = [
    `PK ${(t.pk ?? []).join(', ') || '—'}`,
    ...(t.fks && t.fks.length > 0 ? [`→ ${t.fks.join(', ')}`] : []),
  ].join(' · ');
  lines.push(
    `| \`${t.table_name}\` | ${esc(purpose)} | ${scopeOf(t)} | ${esc(accessOf(t))} | ${esc(keys)} | ${writtenBy} · P${phase} |`,
  );
}

lines.push(
  '',
  `## RPC functions (${functions.length})`,
  '',
  'Signed-in users call these; each is `SECURITY DEFINER` with a pinned `search_path` and checks the caller inside.',
  '',
  '| Function | Arguments |',
  '|---|---|',
);
for (const f of functions) lines.push(`| \`${f.name}\` | \`${esc(f.args)}\` |`);
lines.push('');

writeFileSync('docs/DATA-MODEL.md', lines.join('\n'));
console.log(`Wrote docs/DATA-MODEL.md (${rows.length} tables, ${functions.length} functions).`);
await pool.end();
